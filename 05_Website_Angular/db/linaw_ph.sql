-- ------------------------------------------------------------
-- Skills.  One canonical row per skill; resumes and postings
-- both point at it, so "MySQL" on a resume and "MySQL" on a
-- posting are literally the same row — that IS the match.
-- ------------------------------------------------------------
CREATE TABLE skills (
  skill_id   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  skill_name VARCHAR(120) NOT NULL,
  skill_norm VARCHAR(120) NOT NULL UNIQUE,             -- lowercased, alphanumerics only
  category   TEXT NOT NULL DEFAULT 'technical' CHECK (category IN ('technical','soft'))
);

CREATE TABLE resume_skills (
  resume_id INT NOT NULL REFERENCES resumes(resume_id) ON DELETE CASCADE,
  skill_id  INT NOT NULL REFERENCES skills(skill_id)   ON DELETE CASCADE,
  -- When this skill FIRST appeared on this resume. The rows here are deleted
  -- and rewritten on every save, so routes/resumes.ts carries the existing
  -- value forward rather than letting the default fire again; without that,
  -- an unrelated edit would reset every date and this column would say
  -- nothing. Shown to a recruiter only as context for an interview question,
  -- never used to score, filter or rank.
  added_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  -- WHERE THE APPLICANT USED THIS SKILL: which entry already on their own
  -- resume backs the claim. evidence_kind says which section it points into;
  -- evidence_ref is the label of that entry as the applicant wrote it
  -- ("Web Development Intern, Clark Outsourcing").
  --
  -- Two things about this pair matter enough to write down here:
  --   1. It is NEVER printed on the resume. The printed sheet lists skills
  --      flat, exactly as it always has, so nothing about ATS parsing or the
  --      fourteen designs changes. The evidence is shown only in the
  --      recruiter's applicant view.
  --   2. It DOES affect the score. A matched skill with evidence counts in
  --      full; one without counts at UNEVIDENCED_CREDIT (see lib/engine.ts).
  --      Both are still counted — a skill you cannot point at is not a lie,
  --      it is just weaker proof, and the arithmetic says so.
  evidence_kind TEXT CHECK (evidence_kind IN ('experience','project','certification','education','document')),
  evidence_ref  VARCHAR(200),
  -- A skill can be learned in more than one place (a job AND a school), so the
  -- full list of sources lives here as a JSON array of {kind, ref}. The single
  -- evidence_kind/evidence_ref pair above holds the FIRST of them, kept so any
  -- older reader still sees a source and the "has evidence" check stays cheap.
  -- Scoring only asks whether at least one source exists.
  evidence_sources JSONB,
  PRIMARY KEY (resume_id, skill_id)
);

-- ------------------------------------------------------------
-- Job postings.  application_deadline is optional; past it, the
-- posting stops accepting applications by itself (lazy
-- auto-close — no cron, nothing for HR to remember).
-- ------------------------------------------------------------
CREATE TABLE job_postings (
  posting_id      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id      INT NOT NULL REFERENCES companies(company_id) ON DELETE CASCADE,
  created_by      INT REFERENCES users(user_id) ON DELETE SET NULL,
  title           VARCHAR(160) NOT NULL,
  department      VARCHAR(120),
  employment_type TEXT NOT NULL DEFAULT 'full-time' CHECK (employment_type IN ('full-time','part-time','contract','internship')),
  description     TEXT,
  education_level TEXT NOT NULL DEFAULT 'bachelor' CHECK (education_level IN ('none','highschool','vocational','associate','college_level','bachelor','master')),
  min_experience_months INT NOT NULL DEFAULT 0,
  -- Counts for the two sections scored the way experience is. 0 means the
  -- opening states no requirement, which contributes a full component rather
  -- than a penalty, exactly as an unstated months requirement does.
  min_projects          INT NOT NULL DEFAULT 0,
  min_references        INT NOT NULL DEFAULT 0,
  application_deadline  DATE,
  status          TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open','closed')),
  created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),

  /* ---------------- per-opening scoring weights ----------------
     How much each of the three checks is worth for THIS opening,
     as whole percentages. A developer role can be weighted toward
     skills while a trainee role leans on education.

     ALL THREE NULL means "use the site defaults" from the
     match_settings table. That is the default, and it matters: a
     posting that never customised its weights still follows the
     researcher retuning the study's global values, exactly as
     before this column existed.

     The constraint is here as well as in the application because
     these three numbers scale every score the opening produces. A
     set totalling 90 would quietly compress every applicant's
     score by a tenth, and nothing downstream would look wrong.
     The 10 percent floor is a deliberate policy choice: a
     recruiter may de-emphasise a criterion but may not switch one
     off entirely, so no applicant is ever measured on a scale that
     ignores what they have. */
  weight_skills      SMALLINT,
  weight_education   SMALLINT,
  weight_experience  SMALLINT,

  /* CERTIFICATIONS — the optional fourth component.
     NULL means the same as 0: this opening does not score certifications at
     all, which is the default and what every opening written before this
     column existed carries. That is deliberate rather than lazy — it is what
     lets the three-weight rows already in the table keep totalling 100 and
     keep producing exactly the scores they always have, with no backfill.
     The floor of 10 applies to the original three only: a recruiter may
     decline to score certifications entirely, but may not switch off skills,
     education or experience. */
  weight_certifications SMALLINT,

  /* PROJECTS, LANGUAGES, REFERENCES — three further optional components,
     each behaving exactly as certifications does above. NULL means 0: the
     opening does not score that section at all, which is the default and
     what every opening written before these columns existed carries. The
     floor of 10 stays with the original three only, so a recruiter may
     decline to score any of the four optional sections but may never switch
     off skills, education or experience. */
  weight_projects       SMALLINT,
  weight_languages      SMALLINT,
  weight_references     SMALLINT,
  CONSTRAINT posting_weights_complete CHECK (
    (weight_skills IS NULL AND weight_education IS NULL AND weight_experience IS NULL)
    OR (
      weight_skills IS NOT NULL AND weight_education IS NOT NULL AND weight_experience IS NOT NULL
      AND weight_skills + weight_education + weight_experience
          + COALESCE(weight_certifications, 0) + COALESCE(weight_projects, 0)
          + COALESCE(weight_languages, 0) + COALESCE(weight_references, 0) = 100
      AND weight_skills >= 10 AND weight_education >= 10 AND weight_experience >= 10
      AND COALESCE(weight_certifications, 0) >= 0 AND COALESCE(weight_projects, 0) >= 0
      AND COALESCE(weight_languages, 0) >= 0 AND COALESCE(weight_references, 0) >= 0
    )
  )
);
CREATE INDEX idx_post_status ON job_postings (status);
CREATE INDEX idx_post_company ON job_postings (company_id);

CREATE TABLE posting_skills (
  posting_id INT NOT NULL REFERENCES job_postings(posting_id) ON DELETE CASCADE,
  skill_id   INT NOT NULL REFERENCES skills(skill_id)         ON DELETE CASCADE,
  PRIMARY KEY (posting_id, skill_id)
);

-- The certifications an opening asks for. Free text rather than a foreign key
-- into a catalogue, because a certificate's name is whatever the body issuing
-- it calls it, and there is no closed list to normalise against the way there
-- is for skills. cert_norm is the lowercase-alphanumeric form the engine
-- compares with; the applicant's entry must CONTAIN it to count.
CREATE TABLE posting_certifications (
  posting_id INT NOT NULL REFERENCES job_postings(posting_id) ON DELETE CASCADE,
  cert_name  VARCHAR(160) NOT NULL,
  cert_norm  VARCHAR(160) NOT NULL,
  PRIMARY KEY (posting_id, cert_norm)
);

-- The languages an opening asks for, matched by name the way certifications
-- are. Free text for the same reason: a language has no catalogue to key
-- against the way a skill does.
CREATE TABLE posting_languages (
  posting_id INT NOT NULL REFERENCES job_postings(posting_id) ON DELETE CASCADE,
  lang_name  VARCHAR(80) NOT NULL,
  lang_norm  VARCHAR(80) NOT NULL,
  PRIMARY KEY (posting_id, lang_norm)
);

-- Questions the recruiter writes for one opening and the applicant must
-- answer to apply. Deliberately NOT scored: the compatibility score stays
-- arithmetic over resume fields the applicant can see and check for
-- themselves, and free text is neither. These exist so a recruiter can ask
-- the one or two things a resume never says.
CREATE TABLE posting_questions (
  question_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  posting_id  INT NOT NULL REFERENCES job_postings(posting_id) ON DELETE CASCADE,
  prompt      VARCHAR(300) NOT NULL,
  sort_order  SMALLINT NOT NULL DEFAULT 0,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_pq_posting ON posting_questions (posting_id);

-- A seeker's bookmarked openings.
CREATE TABLE saved_jobs (
  user_id     INT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
  posting_id  INT NOT NULL REFERENCES job_postings(posting_id) ON DELETE CASCADE,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (user_id, posting_id)
);

-- ------------------------------------------------------------
-- Department routing.  An admin assigns one HR person to own a
-- company department (e.g. "Lopez owns IT"); a new application
