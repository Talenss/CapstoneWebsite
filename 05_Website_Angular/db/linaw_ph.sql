  company_id    INT NOT NULL REFERENCES companies(company_id) ON DELETE CASCADE,
  department    VARCHAR(120) NOT NULL,
  user_id       INT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
  assigned_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (company_id, department)
);
CREATE INDEX idx_deptassign_company ON department_assignments (company_id);

-- ------------------------------------------------------------
-- Applications.  Six statuses. One application per person per
-- posting, enforced by the unique key rather than by the app.
-- ------------------------------------------------------------
CREATE TABLE applications (
  application_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  seeker_id      INT NOT NULL REFERENCES users(user_id)          ON DELETE CASCADE,
  resume_id      INT NOT NULL REFERENCES resumes(resume_id)      ON DELETE CASCADE,
  posting_id     INT NOT NULL REFERENCES job_postings(posting_id) ON DELETE CASCADE,
  status         TEXT NOT NULL DEFAULT 'submitted' CHECK (status IN ('submitted','scheduling','initial_interview','testing','shortlisted','final_interview','offer','hired','rejected','withdrawn','review')),
  score_snapshot SMALLINT,                             -- the score at the moment of applying (0..100)
  applied_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (seeker_id, posting_id)
);
CREATE INDEX idx_app_posting ON applications (posting_id);
CREATE INDEX idx_app_status ON applications (status);
CREATE TRIGGER trg_applications_updated BEFORE UPDATE ON applications
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- An answer belongs to the APPLICATION rather than the resume: the same
-- applicant answering the same wording on a different opening is a different
-- answer, and editing a resume afterwards must never rewrite what somebody
-- said at the moment they applied.
CREATE TABLE application_answers (
  application_id INT NOT NULL REFERENCES applications(application_id)   ON DELETE CASCADE,
  question_id    INT NOT NULL REFERENCES posting_questions(question_id) ON DELETE CASCADE,
  answer_text    TEXT NOT NULL,
  PRIMARY KEY (application_id, question_id)
);

-- Every status change is attributable to a named human recruiter.
-- This is the audit trail that backs the paper's claim that the
-- system never decides anything.
CREATE TABLE application_status_history (
  history_id     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  application_id INT NOT NULL REFERENCES applications(application_id) ON DELETE CASCADE,
  old_status     TEXT CHECK (old_status IN ('submitted','scheduling','initial_interview','testing','shortlisted','final_interview','offer','hired','rejected','withdrawn','review')),
  new_status     TEXT NOT NULL CHECK (new_status IN ('submitted','scheduling','initial_interview','testing','shortlisted','final_interview','offer','hired','rejected','withdrawn','review')),
  changed_by     INT REFERENCES users(user_id) ON DELETE SET NULL,   -- the recruiter who did it
  -- WHY, in the recruiter's words, as a fixed code. The trail already said
  -- who and what; without this it could never answer "why did we pass on
  -- them?" three months later, which is the question that actually gets
  -- asked. A code rather than free text so it can be counted, and so a
  -- hurried recruiter cannot type something the company would not want to
  -- stand behind. Optional: a status change is still valid without one.
  reason         TEXT CHECK (reason IN ('not_qualified','failed_requirement','salary_mismatch',
                                        'unreachable','position_filled','stronger_candidate',
                                        'withdrew_interest','other')),
  changed_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_hist_app ON application_status_history (application_id);

-- ------------------------------------------------------------
-- Screening notes.  What a recruiter jots down while working a
-- shortlist: "called 3pm, no answer", "wants 35k, budget is 28".
--
-- Without somewhere to put these, HR keeps a spreadsheet beside
-- the system and the system stops being where the work happens.
--
-- INTERNAL. Never returned to the applicant on any route. That
-- is what makes them worth writing: a note the subject may read
-- is a note nobody writes honestly, and half a recruiter's
-- observations are provisional by nature. Under RA 10173 this is
-- disclosed on the privacy page as recruiter-authored assessment
-- held by the employer, and it is why the column is deliberately
-- free text the recruiter controls rather than anything derived.
-- ------------------------------------------------------------
CREATE TABLE application_notes (
  note_id        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  application_id INT NOT NULL REFERENCES applications(application_id) ON DELETE CASCADE,
  author_id      INT REFERENCES users(user_id) ON DELETE SET NULL,
  body           TEXT NOT NULL,
  created_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_notes_app ON application_notes (application_id);

-- ------------------------------------------------------------
-- Cached scores (optional). The engine computes live; this table
-- exists so the study can show scores over time and so a large
-- applicant pool doesn't need recomputing on every page load.
-- ------------------------------------------------------------
CREATE TABLE match_scores (
  match_id            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  resume_id           INT NOT NULL REFERENCES resumes(resume_id)       ON DELETE CASCADE,
  posting_id          INT NOT NULL REFERENCES job_postings(posting_id) ON DELETE CASCADE,
  compatibility_score SMALLINT NOT NULL,               -- 0..100
  skills_matched      SMALLINT NOT NULL DEFAULT 0,
  skills_required     SMALLINT NOT NULL DEFAULT 0,
  edu_meets           SMALLINT NOT NULL DEFAULT 0,
  exp_meets           SMALLINT NOT NULL DEFAULT 0,
  computed_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (resume_id, posting_id)
);
-- computed_at is bumped explicitly by cacheScore()'s upsert (this table
-- has no updated_at column, so it uses no trigger).

-- ------------------------------------------------------------
