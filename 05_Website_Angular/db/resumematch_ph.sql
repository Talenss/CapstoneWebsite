-- Idempotent full reset of just this app's objects, so re-running the
-- file is safe. (Supabase runs everything in the "public" schema.)
DROP TABLE IF EXISTS
  application_status_history, match_scores, applications, saved_jobs,
  department_assignments, posting_skills, job_postings, resume_skills,
  projects, resume_languages, resume_references,
  certifications, work_experience, education, resumes, email_codes,
  recruiter_requests, users, companies, skills, match_settings CASCADE;
-- Logged-in sessions. Dropped with everything else because re-running this
-- file renumbers user_id from 1: a session cookie issued before the reset
-- would otherwise still resolve, and resolve to whoever now holds that id.
-- The server recreates the table on boot (see the session store in
-- src/server.ts), so there is nothing to define here.
DROP TABLE IF EXISTS user_sessions CASCADE;
DROP FUNCTION IF EXISTS set_updated_at() CASCADE;

-- ------------------------------------------------------------
-- updated_at auto-touch (Postgres has no MySQL-style
-- "ON UPDATE CURRENT_TIMESTAMP"; a trigger does the same job).
-- ------------------------------------------------------------
CREATE FUNCTION set_updated_at() RETURNS trigger AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- ------------------------------------------------------------
-- Companies
-- ------------------------------------------------------------
CREATE TABLE companies (
  company_id    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_name  VARCHAR(160) NOT NULL,
  industry      VARCHAR(120),
  location      VARCHAR(200),
  about         TEXT,
  website       VARCHAR(255),
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ------------------------------------------------------------
-- Users.  One table, three roles.
--   seeker    — self-registers (with email verification)
--   recruiter — PROVISIONED: approved by an admin at /admin
--   admin     — the research team; created only via
--               `npm run create-admin`
-- Boolean-ish columns are SMALLINT (0/1) to match how the code reads
-- and writes them.
-- ------------------------------------------------------------
CREATE TABLE users (
  user_id             INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  role                TEXT NOT NULL DEFAULT 'seeker' CONSTRAINT users_role_check CHECK (role IN ('seeker','recruiter','admin')),
  full_name           VARCHAR(120) NOT NULL,
  email               VARCHAR(160) NOT NULL UNIQUE,
  password_hash       VARCHAR(255) NOT NULL,          -- bcrypt
  active_resume_id    INT,                            -- FK added after `resumes` exists
  company_id          INT REFERENCES companies(company_id) ON DELETE SET NULL,
  position_title      VARCHAR(120),
  verified            SMALLINT NOT NULL DEFAULT 0,    -- a recruiter cannot log in until this is 1
  email_notifications SMALLINT NOT NULL DEFAULT 1,
  created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
  last_login_at       TIMESTAMPTZ
);
CREATE INDEX idx_users_role ON users (role);

-- Public "request recruiter access" submissions, reviewed at /admin.
CREATE TABLE recruiter_requests (
  request_id     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name      VARCHAR(120) NOT NULL,
  email          VARCHAR(160) NOT NULL,
  position_title VARCHAR(120),
  company_id     INT REFERENCES companies(company_id) ON DELETE SET NULL,
  note           TEXT,
  status         TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','approved','declined')),
  requested_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_req_status ON recruiter_requests (status);

-- The 6-digit codes behind email verification (sign-up and email
-- change) and password reset. Rows are short-lived by design.
CREATE TABLE email_codes (
  code_id     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email       VARCHAR(190) NOT NULL,
  purpose     TEXT NOT NULL CHECK (purpose IN ('verify','reset')),
  code        CHAR(6) NOT NULL,
  attempts    SMALLINT NOT NULL DEFAULT 0,
  expires_at  TIMESTAMPTZ NOT NULL,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_email_purpose ON email_codes (email, purpose);

-- ------------------------------------------------------------
-- Resumes.  The DUAL-RESUME MODEL lives here:
--   · the structured columns/children below are what gets SCORED
--   · own_file_* is the applicant's own document — shown to HR,
--     NEVER parsed and NEVER scored (see paper delimitations)
-- ------------------------------------------------------------
CREATE TABLE resumes (
  resume_id     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id       INT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
  title         VARCHAR(120) NOT NULL,
  template_type TEXT NOT NULL DEFAULT 'chronological' CHECK (template_type IN ('chronological','functional','combination')),
  design        TEXT NOT NULL DEFAULT 'classic' CHECK (design IN ('classic','modern','minimal','executive','banner','split','bar','categorized','traditional','clean','compact','senior','graduate','technical')),
  full_name     VARCHAR(120),
  email         VARCHAR(160),
  phone         VARCHAR(40),
  address       VARCHAR(200),
  summary       TEXT,
  headline      VARCHAR(200),
  -- Stored and printed as the full visible URL. A parser routinely drops
  -- href, so a link whose only text is "LinkedIn" is lost entirely.
  linkedin      VARCHAR(300),
  portfolio     VARCHAR(300),
  own_file_name VARCHAR(200),
  own_file_mime VARCHAR(100),
  own_file_size INT,
  own_file_path VARCHAR(255),                          -- server/uploads/, never web-reachable
  own_file_uploaded_at TIMESTAMPTZ,
  -- The applicant's own document, read into structured fields so it can be
  -- scored alongside the resume they built. `own_file_extract` is the same
  -- shape the builder edits; `own_file_extract_status` records WHY it is
  -- empty when it is ('unavailable' = no API key, 'unreadable' = format,
  -- 'failed' = tried and could not), because "no score" and "zero score"
  -- must never look the same to a recruiter.
  own_file_extract        JSONB,
  own_file_extract_status TEXT,
  own_file_extract_at     TIMESTAMPTZ,
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_resume_user ON resumes (user_id);
CREATE TRIGGER trg_resumes_updated BEFORE UPDATE ON resumes
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

ALTER TABLE users
  ADD CONSTRAINT fk_user_active_resume
  FOREIGN KEY (active_resume_id) REFERENCES resumes(resume_id) ON DELETE SET NULL;

CREATE TABLE education (
  education_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  resume_id    INT NOT NULL REFERENCES resumes(resume_id) ON DELETE CASCADE,
  school       VARCHAR(160),
  degree       VARCHAR(160),
  -- SCORED: feeds EDU_RANK for the education quarter of the match.
  level        TEXT NOT NULL DEFAULT 'bachelor' CHECK (level IN ('none','highschool','vocational','associate','bachelor','master')),
  year_grad    VARCHAR(10),
  field        VARCHAR(160),
  location     VARCHAR(160),
  honors       VARCHAR(200),
  sort_order   INT NOT NULL DEFAULT 0
);
CREATE INDEX idx_edu_resume ON education (resume_id);

CREATE TABLE work_experience (
  experience_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  resume_id     INT NOT NULL REFERENCES resumes(resume_id) ON DELETE CASCADE,
  position      VARCHAR(160),
  company       VARCHAR(160),
  -- SCORED: summed for the experience quarter of the match. The dates
  -- below are for the printed sheet only and are never parsed.
  months        INT NOT NULL DEFAULT 0,
  description   TEXT,
  location      VARCHAR(160),
  start_date    VARCHAR(40),
  end_date      VARCHAR(40),
  is_current    SMALLINT NOT NULL DEFAULT 0,
  -- Achievement bullets, newline-separated. description stays as the
  -- prose fallback so resumes written before this keep rendering.
  bullets       TEXT,
  sort_order    INT NOT NULL DEFAULT 0
);
CREATE INDEX idx_exp_resume ON work_experience (resume_id);

CREATE TABLE certifications (
  certification_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  resume_id        INT NOT NULL REFERENCES resumes(resume_id) ON DELETE CASCADE,
  cert_name        VARCHAR(200),
  year_taken       VARCHAR(10),
  issuer           VARCHAR(200),
  credential_id    VARCHAR(120),
  sort_order       INT NOT NULL DEFAULT 0
);
CREATE INDEX idx_cert_resume ON certifications (resume_id);

-- ------------------------------------------------------------
-- Optional resume sections.  Added after the first release, so the
-- boot migration creates them too for databases built earlier.
--
-- None of these are read by the matching engine.  The score comes from
-- skills, education.edu_level and work_experience.months and from nothing
-- else, which is why these could be added without touching the published
-- 50/25/25 formula or its tests.
-- ------------------------------------------------------------
CREATE TABLE projects (
  project_id   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  resume_id    INT NOT NULL REFERENCES resumes(resume_id) ON DELETE CASCADE,
  proj_name    VARCHAR(200),
  proj_role    VARCHAR(160),
  start_date   VARCHAR(40),
  end_date     VARCHAR(40),
  description  TEXT,
  link         VARCHAR(300),
  sort_order   INT NOT NULL DEFAULT 0
);
CREATE INDEX idx_proj_resume ON projects (resume_id);

CREATE TABLE resume_languages (
  language_id  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  resume_id    INT NOT NULL REFERENCES resumes(resume_id) ON DELETE CASCADE,
  lang_name    VARCHAR(120),
  -- Text only ("Native", "Conversational").  Never a rating out of five:
  -- a bar or a star count means nothing to a parser and nothing in
  -- greyscale print.
  proficiency  VARCHAR(120),
  sort_order   INT NOT NULL DEFAULT 0
);
CREATE INDEX idx_lang_resume ON resume_languages (resume_id);

CREATE TABLE resume_references (
  reference_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  resume_id    INT NOT NULL REFERENCES resumes(resume_id) ON DELETE CASCADE,
  ref_name     VARCHAR(160),
  position     VARCHAR(160),
  company      VARCHAR(160),
  email        VARCHAR(190),
  phone        VARCHAR(40),
  sort_order   INT NOT NULL DEFAULT 0
);
CREATE INDEX idx_ref_resume ON resume_references (resume_id);

-- ------------------------------------------------------------
-- Skills.  One canonical row per skill; resumes and postings
-- both point at it, so "MySQL" on a resume and "MySQL" on a
-- posting are literally the same row — that IS the match.
-- ------------------------------------------------------------
CREATE TABLE skills (
  skill_id   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  skill_name VARCHAR(120) NOT NULL,
  skill_norm VARCHAR(120) NOT NULL UNIQUE,             -- lowercased, alphanumerics only
  category   TEXT NOT NULL DEFAULT 'technical' CHECK (category IN ('technical','soft'))
);

CREATE TABLE resume_skills (
  resume_id INT NOT NULL REFERENCES resumes(resume_id) ON DELETE CASCADE,
  skill_id  INT NOT NULL REFERENCES skills(skill_id)   ON DELETE CASCADE,
  PRIMARY KEY (resume_id, skill_id)
);

-- ------------------------------------------------------------
-- Job postings.  application_deadline is optional; past it, the
-- posting stops accepting applications by itself (lazy
-- auto-close — no cron, nothing for HR to remember).
-- ------------------------------------------------------------
CREATE TABLE job_postings (
  posting_id      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id      INT NOT NULL REFERENCES companies(company_id) ON DELETE CASCADE,
  created_by      INT REFERENCES users(user_id) ON DELETE SET NULL,
  title           VARCHAR(160) NOT NULL,
  department      VARCHAR(120),
  employment_type TEXT NOT NULL DEFAULT 'full-time' CHECK (employment_type IN ('full-time','part-time','contract','internship')),
  description     TEXT,
  education_level TEXT NOT NULL DEFAULT 'bachelor' CHECK (education_level IN ('none','highschool','vocational','associate','bachelor','master')),
  min_experience_months INT NOT NULL DEFAULT 0,
  application_deadline  DATE,
  status          TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open','closed')),
  created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_post_status ON job_postings (status);
CREATE INDEX idx_post_company ON job_postings (company_id);

CREATE TABLE posting_skills (
  posting_id INT NOT NULL REFERENCES job_postings(posting_id) ON DELETE CASCADE,
  skill_id   INT NOT NULL REFERENCES skills(skill_id)         ON DELETE CASCADE,
  PRIMARY KEY (posting_id, skill_id)
);

-- A seeker's bookmarked openings.
CREATE TABLE saved_jobs (
  user_id     INT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
  posting_id  INT NOT NULL REFERENCES job_postings(posting_id) ON DELETE CASCADE,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (user_id, posting_id)
);

-- ------------------------------------------------------------
-- Department routing.  An admin assigns one HR person to own a
-- company department (e.g. "Lopez owns IT"); a new application
-- for a posting in that department emails only that person.
-- A department with no owner falls back to notifying every
-- verified recruiter, so nothing is ever silently dropped.
-- ------------------------------------------------------------
CREATE TABLE department_assignments (
  assignment_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id    INT NOT NULL REFERENCES companies(company_id) ON DELETE CASCADE,
  department    VARCHAR(120) NOT NULL,
  user_id       INT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
  assigned_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (company_id, department)
);
CREATE INDEX idx_deptassign_company ON department_assignments (company_id);

-- ------------------------------------------------------------
-- Applications.  Five statuses. One application per person per
-- posting, enforced by the unique key rather than by the app.
-- ------------------------------------------------------------
CREATE TABLE applications (
  application_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  seeker_id      INT NOT NULL REFERENCES users(user_id)          ON DELETE CASCADE,
  resume_id      INT NOT NULL REFERENCES resumes(resume_id)      ON DELETE CASCADE,
  posting_id     INT NOT NULL REFERENCES job_postings(posting_id) ON DELETE CASCADE,
  status         TEXT NOT NULL DEFAULT 'submitted' CHECK (status IN ('submitted','review','shortlisted','rejected','hired','withdrawn')),
  score_snapshot SMALLINT,                             -- the score at the moment of applying (0..100)
  applied_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (seeker_id, posting_id)
);
CREATE INDEX idx_app_posting ON applications (posting_id);
CREATE INDEX idx_app_status ON applications (status);
CREATE TRIGGER trg_applications_updated BEFORE UPDATE ON applications
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- Every status change is attributable to a named human recruiter.
-- This is the audit trail that backs the paper's claim that the
-- system never decides anything.
CREATE TABLE application_status_history (
  history_id     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  application_id INT NOT NULL REFERENCES applications(application_id) ON DELETE CASCADE,
  old_status     TEXT CHECK (old_status IN ('submitted','review','shortlisted','rejected','hired','withdrawn')),
  new_status     TEXT NOT NULL CHECK (new_status IN ('submitted','review','shortlisted','rejected','hired','withdrawn')),
  changed_by     INT REFERENCES users(user_id) ON DELETE SET NULL,   -- the recruiter who did it
  changed_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_hist_app ON application_status_history (application_id);

-- ------------------------------------------------------------
-- Cached scores (optional). The engine computes live; this table
-- exists so the study can show scores over time and so a large
-- applicant pool doesn't need recomputing on every page load.
-- ------------------------------------------------------------
CREATE TABLE match_scores (
  match_id            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  resume_id           INT NOT NULL REFERENCES resumes(resume_id)       ON DELETE CASCADE,
  posting_id          INT NOT NULL REFERENCES job_postings(posting_id) ON DELETE CASCADE,
  compatibility_score SMALLINT NOT NULL,               -- 0..100
  skills_matched      SMALLINT NOT NULL DEFAULT 0,
  skills_required     SMALLINT NOT NULL DEFAULT 0,
  edu_meets           SMALLINT NOT NULL DEFAULT 0,
  exp_meets           SMALLINT NOT NULL DEFAULT 0,
  computed_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (resume_id, posting_id)
);
-- computed_at is bumped explicitly by cacheScore()'s upsert (this table
-- has no updated_at column, so it uses no trigger).

